package org.tdgs.ph.ui.screens

import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.Spacer
import androidx.compose.foundation.layout.height
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.layout.width
import androidx.compose.foundation.lazy.items
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.runtime.collectAsState
import androidx.compose.runtime.getValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import org.tdgs.ph.data.Repository
import org.tdgs.ph.ui.components.PhCard
import org.tdgs.ph.ui.components.Pill
import org.tdgs.ph.ui.theme.LocalMetrics

@Composable
fun InsightsScreen(repo: Repository) {
    val state by repo.state.collectAsState()
    val d = state.dashboard
    Page(repo, "Insights", d?.briefingDay?.let { "Briefing for $it, written on your hub" }) {
        if (d == null) { item { Loading() }; return@Page }
        if (d.briefing.isEmpty()) { item { Empty("No briefing yet. The hub writes one each morning.") }; return@Page }
        items(d.briefing, key = { it.key }) { p ->
            val m = LocalMetrics.current
            val color = when (p.key) { "sleep" -> m.sleep; "recovery" -> m.readiness; "training" -> m.intensity; "more" -> m.battery; else -> m.steps }
            PhCard {
                Pill(p.key.replaceFirstChar { it.uppercase() }, color)
                Spacer(Modifier.height(8.dp))
                p.headline?.let { Text(it, style = MaterialTheme.typography.titleMedium) }
                p.summary?.let { Text(it, style = MaterialTheme.typography.bodyMedium, color = m.muted, modifier = Modifier.padding(top = 6.dp)) }
                p.highlights.forEach { h ->
                    Row(Modifier.padding(top = 6.dp)) {
                        Text("•", color = color)
                        Spacer(Modifier.width(8.dp))
                        Text(h, style = MaterialTheme.typography.bodyMedium)
                    }
                }
                p.focus?.let {
                    Text("Focus", style = MaterialTheme.typography.labelSmall, color = color, modifier = Modifier.padding(top = 12.dp))
                    Text(it, style = MaterialTheme.typography.bodyMedium)
                }
            }
        }
        item {
            Text("Generated by the language model configured on your hub from your own data. Not medical advice.",
                style = MaterialTheme.typography.bodySmall, color = LocalMetrics.current.muted, modifier = Modifier.padding(4.dp))
        }
    }
}
